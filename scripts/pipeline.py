# ---- Timeout helper ----
def run_with_timeout(con, sql, engine, timeout_sec=TIMEOUT_SEC):
    """Execute query with timeout. Returns time in seconds or None."""
    try:
        start = time.perf_counter()
        con.execute(sql).fetchall()
        end = time.perf_counter()
        elapsed = end - start
        if elapsed > timeout_sec:
            return None
        return elapsed
    except Exception:
        return None

