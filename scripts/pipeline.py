def extract_features(sql):
    """Extract 25 numerical features from a SQL query string."""
    sql_upper = sql.upper()

    features = {}

    # 1. Number of JOINs
    features['num_joins'] = len(re.findall(r'\bJOIN\b', sql_upper))

    # 2. Has Subquery
    features['has_subquery'] = 1 if sql_upper.count('SELECT') > 1 else 0

    # 3. Number of WHERE conditions
    where_match = re.search(r'WHERE\s+(.*?)(GROUP BY|ORDER BY|HAVING|LIMIT|$)', sql_upper, re.DOTALL)
    if where_match:
        where_clause = where_match.group(1)
        features['num_conditions'] = where_clause.count(' AND ') + where_clause.count(' OR ') + 1
    else:
        features['num_conditions'] = 0

    # 4. Has GROUP BY
    features['has_groupby'] = 1 if 'GROUP BY' in sql_upper else 0

    # 5. Has ORDER BY
    features['has_orderby'] = 1 if 'ORDER BY' in sql_upper else 0

    # 6. Has HAVING
    features['has_having'] = 1 if 'HAVING' in sql_upper else 0

    # 7. Has LIMIT
    features['has_limit'] = 1 if 'LIMIT' in sql_upper else 0

    # 8. Has DISTINCT
    features['has_distinct'] = 1 if 'DISTINCT' in sql_upper else 0

    # 9. Has LIKE
    features['has_like'] = 1 if 'LIKE' in sql_upper else 0

    # 10. Has EXISTS
    features['has_exists'] = 1 if 'EXISTS' in sql_upper else 0

    # 11. Has CASE/WHEN
    features['has_case'] = 1 if 'CASE' in sql_upper else 0

    # 12. Number of aggregation functions
    features['num_aggregations'] = sum(
        len(re.findall(rf'\b{func}\s*\(', sql_upper))
        for func in ['SUM', 'AVG', 'COUNT', 'MIN', 'MAX']
    )

    # 13. Number of tables referenced
    features['num_tables'] = features['num_joins'] + 1

    # 14. Query length (characters)
    features['query_length'] = len(sql.strip())

    # 15. Number of columns in SELECT
    select_match = re.search(r'SELECT\s+(.*?)\s+FROM', sql_upper, re.DOTALL)
    if select_match:
        features['num_select_cols'] = select_match.group(1).count(',') + 1
    else:
        features['num_select_cols'] = 1

    # 16. Has BETWEEN
    features['has_between'] = 1 if 'BETWEEN' in sql_upper else 0

    # 17. Has IN clause
    features['has_in'] = 1 if re.search(r'\bIN\s*\(', sql_upper) else 0

    # 18. Has LEFT JOIN
    features['has_left_join'] = 1 if 'LEFT JOIN' in sql_upper else 0

    # 19. Join complexity (joins × conditions)
    features['join_complexity'] = features['num_joins'] * features['num_conditions']

    # 20. Query tokens count
    features['num_tokens'] = len(sql.split())

    # 21. Number of string literals
    features['num_string_literals'] = len(re.findall(r"'[^']*'", sql))

    # 22. Number of numeric literals
    features['num_numeric_literals'] = len(re.findall(r'\b\d+\.?\d*\b', sql))

    # 23. Nesting depth
    features['nesting_depth'] = sql_upper.count('SELECT') - 1

    # 24. Has string function
    features['has_string_func'] = 1 if any(f in sql_upper for f in ['SUBSTR', 'LIKE', 'TRIM', 'UPPER', 'LOWER']) else 0

    # 25. Has arithmetic in SELECT
    # features['has_arithmetic'] = 1 if re.search(r'[\*\+\-\/]', sql.split('FROM')[0]) else 0
    select_clause = sql.split('FROM')[0]
    # Remove "SELECT *" pattern before checking
    clean = re.sub(r'SELECT\s+\*', 'SELECT ALL', select_clause, flags=re.IGNORECASE)
    features['has_arithmetic'] = 1 if re.search(r'[\*\+\-\/]', clean) else 0

    return features


