for qid, template in tqdm(TPCH_QUERIES.items(), desc="TPC-H Queries", unit="query"):
    query_errors = 0

    for variant in range(VARIANTS_PER_QUERY):
        try:
            # Generate random parameters
            params = generate_params(qid)
            sql = template.format(**params)
            sql_clean = sql.strip()

            # ---- Measure SQLite ----
            sqlite_times = []
            for _ in range(NUM_RUNS):
                t = run_with_timeout(sqlite_con, sql_clean, 'sqlite')
                if t is None:
                    sqlite_times = None
                    break
                sqlite_times.append(t)

            if sqlite_times is None:
                skipped += 1
                continue
            sqlite_time = statistics.median(sqlite_times)

            # ---- Measure DuckDB ----
            duckdb_times = []
            for _ in range(NUM_RUNS):
                t = run_with_timeout(duck_con, sql_clean, 'duckdb')
                if t is None:
                    duckdb_times = None
                    break
                duckdb_times.append(t)

            if duckdb_times is None:
                skipped += 1
                continue
            duckdb_time = statistics.median(duckdb_times)

            # ---- Extract features ----
            features = extract_features(sql_clean)

            # ---- Build record ----
            record = {
                'query_id': f"Q{qid}",
                'variant': variant,
                'sql': sql_clean,
                'query_hash': hashlib.md5(sql_clean.encode()).hexdigest()[:12],
                'sqlite_time_sec': round(sqlite_time, 6),
                'duckdb_time_sec': round(duckdb_time, 6),
                'speedup_ratio': round(sqlite_time / duckdb_time, 4) if duckdb_time > 0 else 0,
                'faster_engine': 'duckdb' if duckdb_time < sqlite_time else 'sqlite',
            }
            record.update(features)
            all_records.append(record)

        except Exception as e:
            query_errors += 1
